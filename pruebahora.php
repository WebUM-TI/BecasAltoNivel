                  <h3>Requisitos para la aplicación de maestrías</h3>
                  <hr style="border: 2px solid #A8CF45; width: 15%;">
                  <div style="width: 90%; padding: 10px 10px 10px 10px; margin: 0 auto;">
                  <p style="text-align: left;">El aspirante deberá suministrar la siguiente documentación en archivos con formato PDF:</p>
                    <ul>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Registro civil de nacimiento. </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> El aspirante deberá presentar la fotocopia (ampliada al 150) de la cédula de ciudadanía por ambas caras. </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Certificado original de residencia o domicilio en el departamento del Huila expedido por la alcaldía municipal respectiva. Puede consultar la forma de obtención en el siguiente enlace <a href="https://certificadoderesidencia.com/colombia/neiva-huila/" target="_blank"><u>https://certificadoderesidencia.com/colombia/neiva-huila/</u></a></p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Diligenciar el formulario de registro a la convocatoria <a href="#Registro"><u>https://umanizales.edu.co/becas-alto-nivel/</u></a></p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Certificado de admisión expedido por Registro Académico de la Universidad de Manizales a uno de los programas de doctorado ofertados en la presente convocatoria. Para iniciar el proceso de admisión ingrese al siguiente enlace <a href="https://sigum.umanizales.edu.co/vinculacion/" target="_blank"><u>(https://sigum.umanizales.edu.co/vinculacion/)</u></a>. El valor de la inscripción al programa no está cubierto por el crédito educativo condonable. </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Diploma o acta de grado de pregrado.  </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Presentar diligenciado el formato requisito de vinculación - realización de actividades de CTeI con sus debidos soportes (Anexo 1). (<a href="https://umanizales.edu.co/wp-content/uploads/2014/12/Anexo-1.RequisitoVinculacion_RealizacionActividades.docx"><u>Descarque aquí el Anexo 1</u></a>) debe ser diligenciado y adjuntado </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Presentar diligenciado el formato perfil de la propuesta de investigación articulada con una o más de los sectores priorizados en la agenda regional de productividad y competitividad (<a href="https://umanizales.edu.co/wp-content/uploads/2014/12/Anexo-2.-Perfil-de-la-propuesta-de-investigacion.docx"><u>Descarque aquí el Anexo 2</u></a>) debe ser diligenciado y adjuntado.</p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Certificado de promedio de notas de pregrado expedido por la Universidad donde cursó el programa.  </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> En caso de hacer parte de la base Nacional del Sistema de Selección de Beneficiarios para Programas Sociales- SISBEN, anexar certificación suministrada por el Departamento Nacional de Planeación  – DNP, a la última fecha de corte. Puede consultarlo en: <a href="https://www.sisben.gov.co/Paginas/consulta-tu-grupo.aspx" target="_blank"><u>https://www.sisben.gov.co/Paginas/consulta-tu-grupo.aspx</u></a></p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> En caso de autoreconocerse como miembro de la población negra, afrocolombiana, raizal y palenquera, anexar certificación de autorreconocimiento expedido por Ministerio del Interior. Puede consultarlo en: <a href="https://datos.mininterior.gov.co/VentanillaUnica/dacnrp/auto-reconocimiento/registro" target="_blank"><u>https://datos.mininterior.gov.co/VentanillaUnica/dacnrp/auto-reconocimiento/registro</u></a>  </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> En caso de haber sufragado en las últimas elecciones presidenciales, anexar fotocopia del certificado electoral.  </p></li>
                    </ul>
