                  <h3>Requisitos mínimos</h3>
                  <hr style="border: 2px solid #A8CF45; width: 15%;">
                  <div style="width: 90%; padding: 10px 10px 10px 10px; margin: 0 auto;">
                    <ul>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Haber nacido en Colombia.</p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Ser residente o haber nacido en el departamento del Huila.</p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Contar con título de pregrado debidamente certificado y reconocido por el Ministerio de Educación Nacional. En caso de haber realizado los estudios de pregrado en el exterior, deberá contar con el título convalidado por el Ministerio de Educación Nacional y adjuntar la resolución respectiva.</p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Tener título profesional..</p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Estar vinculado a entidades u organizaciones del sector productivo de la región y/o a una entidad reconocida por el Sistema Nacional de Ciencia, Tecnología e Innovación (SNCTI) y/o acreditar productos de CTeI establecidos por Minciencias (Productos de nuevo conocimiento y desarrollo tecnológico, apropiación social del conocimiento o de formación) en beneficio del departamento a través del cual se está presentando a la convocatoria bajo el formato de requisitos de vinculación - realización de actividades.</p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Estar admitido para iniciar estudios de primer semestre a uno de los siguientes programas de la Universidad de Manizales: Maestría en Economía modalidad presencial en alianza con Corhuila, Maestría en Desarrollo Sostenible modalidad presencial en alianza con Corhuila, Doctorado en Desarrollo Sostenible, Doctorado en Administración. </p></li>
                      <li><p style="text-align: left;"><b style="color: #A8CF45; font-weight: 900; font-size: 20px;">-</b> Formular una propuesta de investigación articulada a uno o más de los sectores priorizados en la agenda regional de productividad y competitividad del Departamento del Huila y demandas territoriales definidas por el CODECTI-Huila detalladas en el <a href="#popupAnexo2"><u>Anexo No. 2 PERFIL DE PROPUESTA DE INVESTIGACIÓN</u></a>.</p></li>
                    </ul>
